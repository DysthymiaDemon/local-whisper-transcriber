"""Regenerate the hash-locked requirement files that setup installs from.

Run on a Windows x64 developer machine with Python 3.12 after editing resources/requirements.txt or
resources/requirements-openvino.txt:

    py -3.12 packaging/lock_requirements.py

pip resolves every direct and transitive dependency without installing anything, and the lock records the
exact version and SHA-256 of the wheel this platform would install. Setup then runs pip with
--require-hashes --only-binary=:all: --no-deps, so a changed or unexpected file is refused.
Review the lock diff before committing it: hashing a compromised upload does not make it trustworthy.
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path


PROJECT_ROOT = Path(__file__).resolve().parents[1]
RESOURCES = PROJECT_ROOT / "resources"
BASE_INPUT = RESOURCES / "requirements.txt"
OPENVINO_INPUT = RESOURCES / "requirements-openvino.txt"
BASE_LOCK = RESOURCES / "requirements.lock.txt"
OPENVINO_LOCK = RESOURCES / "requirements-openvino.lock.txt"
# Portable (PyInstaller) build: the base list plus PyInstaller, locked the same way.
BUILD_INPUT = RESOURCES / "requirements-build.txt"
BUILD_LOCK = RESOURCES / "requirements-build.lock.txt"
# Declared dependencies the app must never install. Setup uses --no-deps, so leaving them out of the lock keeps them
# off the laptop; app/bootstrap_launcher.py also deletes copies left by older installs.
EXCLUDED_PACKAGES = {
    # Usage telemetry for OpenVINO's model converter (openvino.tools.ovc), which this app never runs. Without it,
    # OpenVINO uses its built-in no-op stub.
    "openvino-telemetry",
}
HEADER = (
    "# Generated by packaging/lock_requirements.py from {source}. Do not edit by hand.\n"
    "# Windows x64, CPython 3.12. Setup installs with --require-hashes --only-binary=:all: --no-deps.\n"
)


def normalize(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def resolve(*inputs: Path) -> dict[str, tuple[str, str]]:
    """Return {normalized name: (version, sha256)} for every wheel pip would install."""
    with tempfile.TemporaryDirectory() as tmp:
        report = Path(tmp) / "report.json"
        cmd = [
            sys.executable, "-m", "pip", "install", "--dry-run", "--ignore-installed", "--quiet",
            "--only-binary=:all:", "--report", str(report),
        ]
        for path in inputs:
            cmd.extend(["-r", str(path)])
        subprocess.run(cmd, check=True)
        data = json.loads(report.read_text(encoding="utf-8"))
    resolved: dict[str, tuple[str, str]] = {}
    for item in data["install"]:
        metadata = item["metadata"]
        hashes = item["download_info"].get("archive_info", {}).get("hashes", {})
        digest = hashes.get("sha256")
        if not digest:
            raise SystemExit(f"No SHA-256 published for {metadata['name']}; refusing to lock it.")
        name = normalize(metadata["name"])
        if name not in EXCLUDED_PACKAGES:
            resolved[name] = (metadata["version"], digest)
    return resolved


def render(source: Path, packages: dict[str, tuple[str, str]]) -> str:
    lines = [HEADER.format(source=f"resources/{source.name}")]
    for name in sorted(packages):
        version, digest = packages[name]
        lines.append(f"{name}=={version} --hash=sha256:{digest}\n")
    return "".join(lines)


def main() -> int:
    if sys.platform != "win32" or sys.version_info[:2] != (3, 12):
        raise SystemExit("Run this with 64-bit Python 3.12 on Windows so the locked wheels match the laptops.")
    base = resolve(BASE_INPUT)
    combined = resolve(BASE_INPUT, OPENVINO_INPUT)
    conflicts = [name for name in base if name in combined and combined[name] != base[name]]
    if conflicts:
        raise SystemExit(f"OpenVINO packages change shared dependencies: {', '.join(sorted(conflicts))}")
    extra = {name: value for name, value in combined.items() if name not in base}
    build = resolve(BUILD_INPUT)
    build_conflicts = [name for name in base if name in build and build[name] != base[name]]
    if build_conflicts:
        raise SystemExit(f"Build packages change shared dependencies: {', '.join(sorted(build_conflicts))}")
    build_extra = {name: value for name, value in build.items() if name not in base}
    BASE_LOCK.write_text(render(BASE_INPUT, base), encoding="utf-8", newline="\n")
    OPENVINO_LOCK.write_text(render(OPENVINO_INPUT, extra), encoding="utf-8", newline="\n")
    BUILD_LOCK.write_text(render(BUILD_INPUT, build_extra), encoding="utf-8", newline="\n")
    print(
        f"Locked {len(base)} base packages, {len(extra)} OpenVINO packages and {len(build_extra)} build packages."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
